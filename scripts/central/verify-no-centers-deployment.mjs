import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {json,project} from '../homologacao/common.mjs';
import {verifyDiscovery} from '../../server/central/public-discovery.mjs';

const root=path.join(project,'artifacts/multicomputador-0.10.0-rc.10-20261030');
const release=await json(path.join(root,'release.json'));
const deployment=await json(path.join(root,'deployment-result.json'));
const update=await json(path.join(root,'pichau-update.json'));
const installed=await json(path.join(root,'installed-flow-proof.json'));
const loc=await json('artifacts/consulta-ativacao-20261029/location.json');
const profile=await json(path.join(loc.profile,'consultation.json'));
const sha=b=>createHash('sha256').update(b).digest('hex');
if(!deployment.applied||!update.updated||!installed.passed)throw Error('INSTALLED_VALIDATION_REQUIRED');
const installedAsar=sha(await fs.readFile(path.join(update.install,'resources/app.asar')));
if(installedAsar!==sha(await fs.readFile(path.join(root,'build/win-unpacked/resources/app.asar'))))throw Error('INSTALLED_PACKAGE_MISMATCH');
const base='https://api.ruycaldodecana.com.br';
const request=async(route,options={})=>fetch(base+route,{...options,redirect:'error',signal:AbortSignal.timeout(10000)});
const latest=await request('/downloads/latest.json');
if(!latest.ok||(await latest.json()).sha256!==release.sha256)throw Error('PUBLISHED_INSTALLER_MISMATCH');
const binary=await request('/downloads/'+path.basename(release.file),{method:'HEAD'});
if(!binary.ok||Number(binary.headers.get('content-length'))!==release.bytes)throw Error('PUBLISHED_INSTALLER_SIZE_MISMATCH');
const signed=await request('/.well-known/sistema-ruy.json');
const discovery=verifyDiscovery(await signed.json(),{publicKey:profile.discovery.publicKey,deploymentId:profile.discovery.deploymentId,minimumGeneration:profile.discovery.generation});
const headers={'X-Ruy-Sync-Contract':'RUY-SHARED-LAB/1','X-Ruy-Client-Release':release.version};
const connection=await request('/api/local/d1/connection',{headers});
if(!connection.ok||!(await connection.json()).operationalEnabled)throw Error('OPERATIONAL_API_UNAVAILABLE');
const denied=await request('/api/local/d1/state',{headers});
if(denied.status!==401)throw Error('UNAUTHENTICATED_ACCESS_NOT_BLOCKED');
const {stdout}=await promisify(execFile)('powershell.exe',['-NoProfile','-NonInteractive','-Command',"Get-CimInstance Win32_Service | Where-Object {$_.Name -in @('SistemaRuyCentralRc1','SistemaRuyConsultaPostgres')} | Select-Object Name,State,ProcessId | ConvertTo-Json"],{windowsHide:true});
const services=JSON.parse(stdout);
if(services.length!==2||services.some(s=>s.State!=='Running')||services.find(s=>s.Name==='SistemaRuyConsultaPostgres').ProcessId!==24264)throw Error('SERVICE_CONTINUITY_FAILED');
const previous=await json('artifacts/multicomputador-0.10.0-rc.9-20261030/release.json');
if(sha(await fs.readFile(previous.file))!=='00c545c2b7f2d373246403a5e0320cfe4654a3b47b66b97e9433bf9529ede73d')throw Error('RC9_PRESERVATION_FAILED');
const proof={at:new Date().toISOString(),passed:true,version:release.version,httpsStatus:connection.status,unauthenticatedStatus:denied.status,discoverySignatureValid:true,apiOrigin:discovery.endpoint,installedPackageMatchesTested:true,installedFormFlowPassed:true,services,backup:deployment.backup.file,rollback:deployment.rollback,previousClientBackup:update.previousInstallationBackup,rc9Preserved:true,recordsPreserved:deployment.manifest.records,physicalAttachmentsPreserved:deployment.manifest.attachments,paymentsChanged:false,balancesChanged:false,databaseMigrations:false,physicalSecondComputerUpdated:false};
await fs.writeFile(path.join(root,'final-verification.json'),JSON.stringify(proof,null,2));
console.log(JSON.stringify(proof));
