import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {randomUUID,randomBytes,createHash} from 'node:crypto';
import {installation,home,config,unseal,cluster,pgCommand,validateHome} from '../../server/d1-lab/environment.mjs';
import {initializeLab,ensureLocalDatabase} from '../../server/d1-lab/bootstrap.mjs';
import {pg,poolFor} from '../../server/d1-lab/core.mjs';
import {backup,restoreIsolated} from '../../server/d1-lab/backup.mjs';
if(!installation)throw Error('Explicit new installation fixture required');
await fs.mkdir('logs/i5r3',{recursive:true});
const login=installation.id+'@example.invalid',password=randomBytes(24).toString('hex');
// mkdir(home) refuses reuse; never clone a previous installation.
if(!process.argv.includes('--resume-created-fixture'))await initializeLab({bin:'C:/Program Files/PostgreSQL/17/bin',account:{login,password}});
const marker=await validateHome(),credentials=await config();
let pool=poolFor(credentials);
const actor=(await pool.query('SELECT id FROM lab_users WHERE login=$1',[login])).rows[0].id;
const id=randomUUID(),data={name:'FICTICIO isolamento '+installation.id};
await pool.query('INSERT INTO lab_notes(id,owner_id,data) VALUES($1,$2,$3)',[id,actor,data]);
await pool.end();
pgCommand(marker.bin,'pg_ctl',['-D',cluster,'-m','fast','-w','restart']);
await ensureLocalDatabase();pool=poolFor(credentials);
assert.deepEqual((await pool.query('SELECT data FROM lab_notes WHERE id=$1',[id])).rows[0].data,data);
await pool.end();
const encrypted=await backup({preserveExisting:true});
const restored=await restoreIsolated(path.join(home,'backups',encrypted.file));
assert.notEqual(restored.database,credentials.database);
pool=new pg.Pool({...await config(true),database:restored.database});
