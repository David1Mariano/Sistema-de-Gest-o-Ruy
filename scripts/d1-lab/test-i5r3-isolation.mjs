const report={installation:installation.id,home,apiPort:installation.apiPort,dbPort:installation.dbPort,database:credentials.database,deviceId:marker.deviceId,passwordFingerprint:createHash('sha256').update(credentials.password).digest('hex'),certificateFingerprint:certs.client.fingerprint,postgresRestartPersistence:true,encryptedBackupRestore:true,restoredIntoNewDatabase:true,operationalSync:false,syntheticOnly:true};
await fs.writeFile('logs/i5r3/'+installation.id+'.json',JSON.stringify(report,null,2));
console.log('I5R3_ISOLATED_DATA_BACKUP_OK '+installation.id);
