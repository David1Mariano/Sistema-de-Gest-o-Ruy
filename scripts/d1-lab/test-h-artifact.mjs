import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const require=createRequire(new URL('../../desktop/package.json',import.meta.url)),asar=require('@electron/asar');
const file=path.join(root,'artifacts/windows-lab-0.5.0-h1/win-unpacked/resources/app.asar');
const files=asar.listPackage(file).map(f=>f.replaceAll('\\','/'));
for(const required of ['/recovery.html','/recovery-preload.cjs','/recovery-renderer.js','/recovery.mjs','/supervisor.mjs','/server/d1-lab/bootstrap.mjs','/server/d1-lab/key-envelope.mjs'])assert.ok(files.includes(required),required);
assert.equal(files.some(f=>/(?:^|\/)\.env(?:\.|$)|\.(?:dpapi|ruybak|ruykey)$|\/cluster\//i.test(f)),false);
const read=f=>asar.extractFile(file,f.replaceAll('/',path.sep)).toString();
const frontend=files.filter(f=>f.startsWith('/dist-d1/')&&f.endsWith('.js')).map(f=>read(f.slice(1))).join('\n');
assert.equal(frontend.includes('supabase.co'),false);
assert.equal(/ADM-RUY|[A-Za-z]:[/\\]Users[/\\]/.test(read('main.mjs')+read('server/d1-lab/bootstrap.mjs')),false);
const metadata=JSON.parse(read('package.json'));
assert.equal(metadata.version,'0.5.0');assert.equal(metadata.ruyRevision,'H1');assert.equal(metadata.ruyAppId,'br.ruy.gestao.laboratorio.h');
fs.writeFileSync(path.join(root,'logs/etapa-h-artifact.json'),JSON.stringify({requiredFilesPresent:true,privateEnvironmentFilesAbsent:true,supabaseEndpointAbsent:true,machineSpecificRuntimePathsAbsent:true,version:metadata.version,revision:metadata.ruyRevision},null,2));
console.log('H_ARTIFACT_OK');
