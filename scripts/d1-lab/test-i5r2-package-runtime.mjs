import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {spawn} from 'node:child_process';
const executable=path.resolve('artifacts/agente5-integracao5r2-20261020/win-unpacked/Sistema Ruy - I5 R2 Homologacao.exe');
const profile=path.join(process.env.APPDATA,'SistemaGestaoRuy-Agente5-I5R2-Homolog');
const clean={...process.env};for(const key of Object.keys(clean))if(key.startsWith('RUY_'))delete clean[key];delete clean.ELECTRON_RUN_AS_NODE;
const run=(args,env=clean)=>new Promise((r,j)=>{const child=spawn(executable,args,{windowsHide:false,stdio:'ignore',env});child.once('error',j);child.once('exit',r);});
assert.equal(await run(['--lab-window-test']),0);
const window=JSON.parse(await fs.readFile(path.join(profile,'window-test.json'),'utf8'));
assert.equal(window.packaged,true);assert.equal(window.hiddenWindowRecoveredBySecondInstance,true);
assert.equal(await run(['--lab-startup-failure-test']),1);
assert.equal(await run(['--lab-startup-failure-test'],{...clean,RUY_D1_TEST_API_PORT:'18087'}),1);
const rows=(await fs.readFile(path.join(profile,'startup.jsonl'),'utf8')).trim().split('\n').map(line=>JSON.parse(line));
assert.ok(rows.some(row=>row.event==='startup-failed'&&row.errorCode==='LAB_STARTUP_TEST'));
assert.ok(rows.some(row=>row.event==='entry-failed'));
assert.ok(rows.some(row=>row.event==='shutdown-complete'));
const result={actualPackagedElectron:true,installed:false,launcherRuyVariablesRemoved:true,window,syntheticStartupFailureExitCode:1,invalidEnvironmentExitCode:1,shutdownCompleteLogged:true,existingLabApi18091Reused:true,realOwnedApiShutdownTested:false,noProcessForced:true};
await fs.writeFile('logs/i5r2/runtime.json',JSON.stringify(result,null,2));console.log('I5R2_RUNTIME_OK');
